package org.lynxsdk.library

class LynxLibraryRegistryGenerator {
    static final String REGISTRY_PACKAGE_NAME = 'com.lynx.tasm.library'
    static final String REGISTRY_CLASS_NAME = 'LynxAutolinkGenerated'

    static String generate(List<LynxLibraryInfo> libraries) {
        return generateRegistry(libraries)
    }

    static String generateRegistry(List<LynxLibraryInfo> libraries) {
        String providerEntries = libraries.findAll {
            it.providerClassName != null
        }.collect {
            "      \"${it.providerClassName}\""
        }.join(',\n')
        if (providerEntries.length() == 0) {
            providerEntries = ''
        }
        List<LynxNodeApiAddonInfo> nodeApiAddons = []
        libraries.each { LynxLibraryInfo library ->
            nodeApiAddons.addAll(library.nodeApiAddons)
        }
        String nodeApiAddonEntries = nodeApiAddons.collect {
            "      new NodeApiAddon(\"${it.name}\", \"${it.libraryName}\", ${it.required})"
        }.join(',\n')
        if (nodeApiAddonEntries.length() == 0) {
            nodeApiAddonEntries = ''
        }
        """// Generated by org.lynxsdk.library. Do not edit.
package ${REGISTRY_PACKAGE_NAME};

import android.content.Context;
import android.util.Log;
import androidx.annotation.Keep;
import com.lynx.tasm.LynxViewBuilder;

@Keep
public final class ${REGISTRY_CLASS_NAME} {
  private static final String TAG = "LynxAutolinkGenerated";

  private static final String[] PROVIDERS = new String[] {
${providerEntries}
  };

  private static final NodeApiAddon[] NODE_API_ADDONS = new NodeApiAddon[] {
${nodeApiAddonEntries}
  };

  private ${REGISTRY_CLASS_NAME}() {}

  public static void setupGlobal(Context context) {
    loadNodeApiAddons();
    LynxLibraryRegistry.setupGlobal(context, PROVIDERS);
  }

  public static void setup(LynxViewBuilder builder) {
    LynxLibraryRegistry.setup(builder, PROVIDERS);
  }

  private static void loadNodeApiAddons() {
    for (NodeApiAddon addon : NODE_API_ADDONS) {
      try {
        System.loadLibrary(addon.libraryName);
      } catch (UnsatisfiedLinkError error) {
        if (addon.required) {
          throw error;
        }
        Log.w(TAG, "Failed to load optional Lynx Node-API addon " + addon.name, error);
      }
    }
  }

  private static final class NodeApiAddon {
    final String name;
    final String libraryName;
    final boolean required;

    NodeApiAddon(String name, String libraryName, boolean required) {
      this.name = name;
      this.libraryName = libraryName;
      this.required = required;
    }
  }
}
"""
    }
}

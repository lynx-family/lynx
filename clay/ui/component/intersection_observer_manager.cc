constexpr double kLargeExposureTargetViewportAreaRatio = 0.5;

bool HasValidPositiveArea(const BaseView* view) {
  return view && std::isfinite(view->Width()) &&
         std::isfinite(view->Height()) && view->Width() > 0 &&
         view->Height() > 0;
}

double Area(const BaseView* view) {
  return static_cast<double>(view->Width()) *
         static_cast<double>(view->Height());
}

void TraceFirstAddDecision(const BaseView* target, const BaseView* page_view,
                           bool has_exposure_observer, bool has_uiappear,
                           const char* decision, const char* reason) {
  const bool valid_target_layout = HasValidPositiveArea(target);
  const bool valid_page_layout = HasValidPositiveArea(page_view);
  const bool direct_page_child =
      target && page_view && target->Parent() == page_view;
  const bool candidate =
      direct_page_child && has_exposure_observer && has_uiappear;
  const double target_area_ratio = valid_target_layout && valid_page_layout
                                       ? Area(target) / Area(page_view)
                                       : -1.0;
  TRACE_EVENT_INSTANT(
      "clay", CLAY_FAST_EXPOSURE_FIRST_ADD_DECISION, "target_view_id",
      target ? target->id() : -1, "parent_view_id",
      target && target->Parent() ? target->Parent()->id() : -1, "page_view_id",
      page_view ? page_view->id() : -1, "direct_page_child", direct_page_child,
      "candidate", candidate, "has_exposure_observer", has_exposure_observer,
      "has_uiappear", has_uiappear, "attached",
      target && target->attach_to_tree(), "valid_target_layout",
      valid_target_layout, "valid_page_layout", valid_page_layout,
      "target_width", target ? target->Width() : 0, "target_height",
      target ? target->Height() : 0, "page_width",
      page_view ? page_view->Width() : 0, "page_height",
      page_view ? page_view->Height() : 0, "target_area_ratio",
      target_area_ratio, "decision", decision, "reason", reason);
}


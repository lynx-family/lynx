"""Generate the CSS keyword lookup table with the host's gperf tool."""

import argparse
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile


CLAY_LICENSE = """// Copyright 2026 The Lynx Authors. All rights reserved.
// Licensed under the Apache License Version 2.0 that can be found in the
// LICENSE file in the root directory of this source tree.

//
// DO NOT MODIFY THIS FILE! AUTO GENERATED BY Clay keyword code generation.
//
"""

CLAY_GPERF_TEMPLATE = """%%language=C++
%%define class-name KeywordHash
%%define lookup-function-name find
%%define string-pool-name StringPool
%%struct-type
%%global-table
%%readonly-tables
%%pic

%%{
%(license)s
#include "clay/ui/component/keywords.h"

#include <string>

namespace clay {
%%}

struct TokenValue {
  short name;
  short id;
};

%%%%
%(entries)s
%%%%

static_assert(sizeof(StringPool_contents) < 32767);

KeywordID GetKeywordID(const std::string& str) {
  auto* token = KeywordHash::find(str.c_str(), str.size());
  return token ? static_cast<KeywordID>(token->id) : KeywordID::kInvalid;
}

}  // namespace clay
"""


def find_gperf(buildtools_dir):
    if sys.platform == "darwin":
        return "/usr/bin/gperf"
    executable = "gperf.exe" if sys.platform == "win32" else "gperf"
    packaged = Path(buildtools_dir) / "gperf" / "bin" / executable
    if packaged.is_file():
        return str(packaged.resolve())
    installed = shutil.which(executable)
    if installed:
        return installed
    raise FileNotFoundError(
        "gperf was not found. Sync the build tools or set gperf_executable "
        "to the host gperf binary in args.gn.")


def run_gperf(gperf, template, arguments):
    gperf = os.path.abspath(gperf)
    template = Path(template).resolve()
    generated = subprocess.check_output(
        [gperf, *arguments, template.name], cwd=template.parent,
        text=True, encoding="utf-8")
    # gperf 3.0.x (macOS and Windows) emits the removed C++17 keyword.
    generated = re.sub(r"\bregister\s+", "", generated)
    # Newer gperf releases already emit fallthrough attributes.
    if "__fallthrough__" not in generated and "[[fallthrough]]" not in generated:
        generated = generated.replace("/*FALLTHROUGH*/", "[[fallthrough]];")
    return generated


def write_if_changed(output, generated):
    output = Path(output)
    if output.exists() and output.read_text(encoding="utf-8") == generated:
        return
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", encoding="utf-8", newline="\n") as destination:
        destination.write(generated)


def generate(gperf, template, output):
    generated = run_gperf(gperf, template, ["-D", "-t"])
    generated = re.sub(r"^/\* Command-line: .*\*/$",
                       "/* Generated from css_keywords.tmpl. Do not edit. */",
                       generated, flags=re.MULTILINE)
    write_if_changed(output, generated)


def camel_case_name(name):
    return "".join(word.capitalize() for word in name.split("-"))


def read_keyword_list(path):
    keywords = []
    seen = set()
    with Path(path).open(encoding="utf-8") as source:
        for line_number, line in enumerate(source, 1):
            keyword = line.strip()
            if not keyword or keyword.startswith("//"):
                continue
            if keyword in seen:
                raise ValueError(
                    f"{path}:{line_number}: duplicate keyword: {keyword}"
                )
            seen.add(keyword)
            keywords.append(keyword)
    if not keywords:
        raise ValueError(f"No keywords found in {path}")
    return keywords


def generate_clay_keywords(gperf, keyword_list, header_template,
                           header_output, source_output):
    keywords = read_keyword_list(keyword_list)
    header = Path(header_template).read_text(encoding="utf-8")
    if header.count("{{ id_list }}") != 1:
        raise ValueError(
            f"{header_template}: expected exactly one {{{{ id_list }}}}"
        )
    identifiers = ",\n".join(
        f"  k{camel_case_name(keyword)}" for keyword in keywords
    )
    write_if_changed(header_output, header.replace("{{ id_list }}", identifiers))

    entries = "\n".join(
        f"{keyword}, (short)KeywordID::k{camel_case_name(keyword)}"
        for keyword in keywords
    )
    contents = CLAY_GPERF_TEMPLATE % {
        "license": CLAY_LICENSE,
        "entries": entries,
    }
    with tempfile.TemporaryDirectory() as temporary_dir:
        template = Path(temporary_dir) / "keywords.gperf"
        template.write_text(contents, encoding="utf-8")
        generated = run_gperf(gperf, template, ["-m", "100"])
    lines = []
    for line in generated.splitlines(True):
        if line.startswith("#line") or line.startswith("/* Command-line:"):
            continue
        lines.append(line.replace("(int)", "(short)"))
    write_if_changed(source_output, "".join(lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--find-gperf", metavar="BUILDTOOLS_DIR")
    parser.add_argument("--gperf", help="Path to the host gperf executable")
    parser.add_argument("--input", help="Path to css_keywords.tmpl")
    parser.add_argument("--output", help="Path to the generated C++ source")
    parser.add_argument("--clay-keyword-list")
    parser.add_argument("--header-template")
    parser.add_argument("--header-output")
    parser.add_argument("--source-output")
    args = parser.parse_args()
    try:
        if args.find_gperf:
            print(find_gperf(args.find_gperf))
            return
        if args.clay_keyword_list:
            required = (
                args.header_template,
                args.header_output,
                args.source_output,
            )
            if not all(required):
                parser.error(
                    "--clay-keyword-list requires --header-template, "
                    "--header-output, and --source-output"
                )
            gperf = args.gperf or find_gperf(
                Path(__file__).resolve().parents[2] / "buildtools")
            generate_clay_keywords(
                gperf,
                args.clay_keyword_list,
                args.header_template,
                args.header_output,
                args.source_output,
            )
            return
        if not args.input or not args.output:
            parser.error("--input and --output are required")
        gperf = args.gperf or find_gperf(
            Path(__file__).resolve().parents[2] / "buildtools")
        generate(os.path.abspath(gperf), args.input, args.output)
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        parser.exit(1, f"Keyword generation failed: {error}\n")


if __name__ == "__main__":
    main()
